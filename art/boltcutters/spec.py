def to_roblox(v):
    """Blender's (x, y, z) to Roblox's: x = -x, y = z, z = y."""
    return (-v[0], v[2], v[1])


def write_luau(path, body):
    """body: dict(size, centre, tris) in Roblox axes, from the grip."""

    def v3(v):
        return f"Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})"

    tip = to_roblox((0.0, JAW[0][0] - GRIP_Y, 0.0))
    head = to_roblox((0.0, -GRIP_Y, 0.0))
    lines = [
        "--!strict",
        "-- Generated by art/boltcutters/build.py --stage export from art/boltcutters/spec.py.",
        "-- Don't edit: change the spec and rebuild (scripts/art.sh boltcutters).",
        "-- Studs, in the cutters' own frame: the jaw towards the LookVector (-Z), the head's plates",
        "-- up (+Y), every point measured from the grip, where the hand closes round both grips.",
        "",
        "export type Piece = {",
        "\tSize: Vector3, -- the piece's box",
        "\tCentre: Vector3, -- the box's middle, from the grip",
        "\tTriangles: number,",
        "}",
        "",
        "return {",
        f"\tBody = {{ Size = {v3(body['size'])}, Centre = {v3(body['centre'])}, "
        f"Triangles = {body['tris']} }} :: Piece,",
        "\t-- the jaw's tip, where it bites a shackle",
        f"\tJawTip = {v3(tip)},",
        "\t-- the middle of the head, between the plates",
        f"\tHead = {v3(head)},",
        "}",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("SPEC", path)
