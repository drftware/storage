"""The storage unit's numbers: one source of truth for the Blender build and the game.

Units are studs. Blender axes, as the Roblox FBX recipe wants them (Forward = Z, Up = Y):
    +X  across the door, the hallway viewer's right    (Roblox -X)
    -Y  out of the unit, toward the hallway             (Roblox -Z, LookVector)
    +Z  up                                              (Roblox +Y)
The unit's origin is the middle of its doorway's outer face, on the floor. The corridor wall's
outer face is the plane Y = 0 and the unit runs back to Y = depth.

`write_luau` turns a built spec into `src/shared/StorageUnit/Specs/<Size>.luau`.
"""

import math

from curtain import Curtain

# Three sizes, GDD "Units come in three sizes". Footprints are wall centre to wall centre.
SIZES = {
    "S": dict(width=8.0, depth=8.0, door_width=6.0),      # ~5x5 ft with partitions
    "M": dict(width=12.0, depth=12.0, door_width=8.0),    # the 10x10, the hero
    "L": dict(width=16.0, depth=20.0, door_width=12.0),   # ~10x20
}

COMMON = dict(
    wall_height=10.0,        # partitions; the wire top sits on them
    door_height=8.0,         # clear opening under the header trim
    facade=0.25,             # corridor wall thickness
    curtain_y=0.55,          # curtain plane, behind the facade's outer face
    trim=0.45,               # jamb and header trim face width
    trim_proud=0.05,
    pilaster=0.25,           # half a post at each side; neighbours make it whole
    kick=0.7,                # kick plate height
    # curtain
    pitch=0.30,              # one rib per slat
    rib=0.05,                # rib depth (outward)
    sheet=0.016,             # steel thickness
    into_guide=0.32,         # curtain overlap into each guide
    guide_top=8.30,
    drum_up=8.95,
    drum_back=0.55,          # drum axis behind the curtain plane
    drum_r=0.28,
    wrap=0.075,              # coil growth per turn
    residual_turns=1.30,     # turns left on the drum when shut
    gap=0.06,                # light gap under the shut door (GDD: watch hall lights through it)
    seal=0.10,               # rubber astragal
    bar=0.20,                # bottom bar body
    travel=7.65,             # full open rise; the bar stops just under the header
    peek=1.15,               # GDD: lift the door a foot and crouch
)


class Spec:
    def __init__(self, size="M"):
        self.size = size
        for k, v in {**COMMON, **SIZES[size]}.items():
            setattr(self, k, v)
        self.curtain_width = self.door_width + 2.0 * self.into_guide
        self.bottom_closed = self.gap + self.seal + self.bar  # curtain's bottom edge, shut
        # Slat count: hanging + run to the coil + the residual turns, rounded up to whole ribs.
        probe = Curtain(pitch=self.pitch, count=1, bottom_closed=self.bottom_closed,
                        guide_top=self.guide_top, drum_z=-self.drum_back, drum_y=self.drum_up,
                        r0=self.drum_r, wrap=self.wrap)
        phi = self.residual_turns * 2.0 * math.pi
        _, ell = probe._tangent(probe.radius(phi))
        need = (self.guide_top - self.bottom_closed) + ell + probe.arc(phi)
        self.slat_count = int(math.ceil(need / self.pitch))
        self.curtain = Curtain(pitch=self.pitch, count=self.slat_count,
                               bottom_closed=self.bottom_closed, guide_top=self.guide_top,
                               drum_z=-self.drum_back, drum_y=self.drum_up,
                               r0=self.drum_r, wrap=self.wrap).prime()

    # door-local (z_out, y) -> Blender (Y, Z)
    def to_blender(self, z_out, y):
        return (self.curtain_y - z_out, y)

    @property
    def drum_center(self):
        return (0.0, self.curtain_y + self.drum_back, self.drum_up)

    def slat_variant(self, index, seed):
        """Which slat mesh sits at chain index `index`: bottom three ribs are the grimy C."""
        if index < 3:
            return "C"
        h = (index * 2654435761 + seed * 40503) & 0xFFFF
        return "A" if (h >> 7) & 1 else "B"


def lua_num(v):
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def write_luau(spec, path, extra):
    """Write the game's copy of this spec. `extra` holds measured values (template rest poses)."""
    c = spec.curtain
    lines = [
        "--!strict",
        f"-- GENERATED by art/unit/build.py from art/unit/spec.py (size {spec.size}). Do not edit.",
        "-- Studs. Door-local frame: origin at the bottom middle of the opening on the curtain",
        "-- plane; +Y up, -Z out toward the hallway (the DoorOrigin part's LookVector).",
        "",
        "return {",
        f'\tSize = "{spec.size}",',
        f"\tWidth = {lua_num(spec.width)},",
        f"\tDepth = {lua_num(spec.depth)},",
        f"\tWallHeight = {lua_num(spec.wall_height)},",
        f"\tDoorWidth = {lua_num(spec.door_width)},",
        f"\tDoorHeight = {lua_num(spec.door_height)},",
        f"\tCurtainWidth = {lua_num(spec.curtain_width)},",
        f"\tCurtainPlane = {lua_num(spec.curtain_y)}, -- behind the facade's outer face",
        "",
        "\tCurtain = {",
        f"\t\tPitch = {lua_num(c.pitch)},",
        f"\t\tCount = {c.count},",
        f"\t\tBottomClosed = {lua_num(c.bottom_closed)},",
        f"\t\tGuideTop = {lua_num(c.guide_top)},",
        f"\t\tDrumZ = {lua_num(c.cz)}, -- outward is +z in the solver's plane",
        f"\t\tDrumY = {lua_num(c.cy)},",
        f"\t\tDrumRadius = {lua_num(c.r0)},",
        f"\t\tWrap = {lua_num(spec.wrap)},",
        "\t},",
        "",
        "\tRise = {",
        f"\t\tPeek = {lua_num(spec.peek)},",
        f"\t\tOpen = {lua_num(spec.travel)},",
        "\t},",
        f"\tGap = {lua_num(spec.gap)}, -- under the shut door",
        f"\tBarBottomClosed = {lua_num(spec.gap)},",
        f"\tBarTopClosed = {lua_num(spec.bottom_closed)},",
        "",
        "\t-- Slat mesh per chain index, bottom first (A and B clean, C the grimy bottom ribs).",
        "\tSlatOrder = { " + ", ".join(f'"{spec.slat_variant(i, 7)}"' for i in range(c.count)) + " },",
        "",
        "\t-- Where each exported moving part rests when the door is shut, in the door-local",
        "\t-- frame. RollUpDoor calibrates against these, whatever pivots the importer picks.",
        "\tRest = {",
    ]
    for name, (pos, rx) in extra["rest"].items():
        lines.append(f"\t\t{name} = {{ Position = Vector3.new({', '.join(lua_num(v) for v in pos)}), "
                     f"RotX = {lua_num(rx)} }},")
    lines += [
        "\t},",
        "",
        "\t-- The bolt rests shot (locked). Unlocked = rest moved by (LatchThrow, 0, 0) in door-local X.",
        f"\tLatchThrow = {lua_num(extra['latch_throw'])},",
        "",
        "\t-- Collision boxes in the unit's frame (origin: doorway middle, floor; -Z hallway).",
        "\tColliders = {",
    ]
    for name, (cf, size) in extra["colliders"].items():
        lines.append(f"\t\t{name} = {{ Position = Vector3.new({', '.join(lua_num(v) for v in cf)}), "
                     f"Size = Vector3.new({', '.join(lua_num(v) for v in size)}) }},")
    lines += [
        "\t},",
        "",
        "\t-- Number plate face (SurfaceGui), in studs.",
        f"\tPlateSize = Vector2.new({lua_num(extra['plate'][0])}, {lua_num(extra['plate'][1])}),",
        "",
        "\tTriangles = {",
    ]
    for name, n in sorted(extra["tris"].items()):
        lines.append(f"\t\t{name} = {n},")
    lines += ["\t},", "}", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
