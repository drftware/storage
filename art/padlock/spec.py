"""Every number of the padlock you carry, in studs. Change them here only.

The padlock the building hangs on its doors (art/unit/parts.py, `padlock`), in your hand: a
laminated steel body of six plates riveted through, a hardened steel shackle and a brass keyway
underneath. Yours is open, its shackle up and swung out to the side, ready to snap shut on a
door (GDD, the tools table: "Locks a door so a trapped keeper stays trapped").

Sized to be seen rather than to life, as the torch and the cutters are: twice the doors'
padlocks, 0.44 studs across the body, so it reads lying on a unit's floor on a phone, in a
friend's fist and in the corner of your own view.

The padlock's frame in Blender: X across the body, Y through it (its face at -Y, the front),
Z up (the shackle), the origin the grip (the body's middle, where the hand closes). The FBX turns
this into Roblox's frame (Y up, the face towards the part's LookVector), and the game reads the
numbers from src/shared/Tools/Specs/Padlock.luau, which the export stage writes.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

SET = "Padlock"   # the texture set, and the MeshPart's name
TEX = 1024        # seen close in your hand: the cutters' atlas size
DUST = 0.06       # a tool left on a unit's floor: a little dust on its top
SEED = 47.0

S = 2.0           # times the doors' padlocks (art/unit/parts.py)

# The body: six steel plates stacked, riveted through at both ends, a thin cap plate on top.
BODY_W = 0.22 * S         # across (X)
BODY_T = 0.09 * S         # front to back (Y)
LAMS = 6
LAM_H = 0.03 * S          # each plate's height
LAM_BEVEL = 0.006 * S
BODY_H = LAMS * LAM_H     # 0.27
CAP_H = 0.006 * S         # the cap on the top plate, where the shackle goes in
CAP_IN = 0.01 * S         # how far the cap sits in from the body's sides
CAP_TOP = BODY_H / 2 + CAP_H

RIVET_X = BODY_W / 2 - 0.028   # the rivets' heads, top and bottom, near each end
RIVET_R = 0.013

# The shackle: a hardened steel bar bent in a U. Its legs stand SHACKLE_R either side of the
# middle; the long leg (+X) stays in the body, the short one (-X) comes out of its hole.
SHACKLE_R = 0.07 * S          # the bend's radius: half the gap between the legs
SHACKLE_TUBE = 0.017 * S      # the bar's radius
SHACKLE_CLEAR = 0.04 * S      # straight leg above the cap, shut, before the bend
SHACKLE_IN = 0.02             # how deep the short leg sits in its hole, shut
# Open: the shackle rises LIFT so the short leg clears its hole, then swings SWING degrees round
# the long leg, out to the side, as an open padlock is drawn.
LIFT = 0.05 * S
SWING = 180.0

# The keyway: a brass cylinder in the bottom plate, standing a little proud.
KEY_R = 0.028 * S
KEY_PROUD = 0.008 * S
KEY_SLOT = (0.034 * S, 0.006 * S)   # the key's slot across the brass face: long, wide


def shut_top():
    """The top of the shackle's bend when shut, above the grip."""
    return CAP_TOP + SHACKLE_CLEAR + SHACKLE_R + SHACKLE_TUBE


def to_roblox(v):
    """Blender's (x, y, z) to Roblox's: x = -x, y = z, z = y."""
    return (-v[0], v[2], v[1])


def write_luau(path, body):
    """body: dict(size, centre, tris) in Roblox axes, from the grip."""

    def v3(v):
        return f"Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})"

    hole = to_roblox((-SHACKLE_R, 0.0, CAP_TOP))
    lines = [
        "--!strict",
        "-- Generated by art/padlock/build.py --stage export from art/padlock/spec.py.",
        "-- Don't edit: change the spec and rebuild (scripts/art.sh padlock).",
        "-- Studs, in the padlock's own frame: its face towards the LookVector (-Z), the shackle",
        "-- up (+Y), every point measured from the grip, the body's middle.",
        "",
        "export type Piece = {",
        "\tSize: Vector3, -- the piece's box",
        "\tCentre: Vector3, -- the box's middle, from the grip",
        "\tTriangles: number,",
        "}",
        "",
        "return {",
        f"\tBody = {{ Size = {v3(body['size'])}, Centre = {v3(body['centre'])}, "
        f"Triangles = {body['tris']} }} :: Piece,",
        "\t-- the hole the open shackle's short leg snaps into",
        f"\tHole = {v3(hole)},",
        "}",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("SPEC", path)
