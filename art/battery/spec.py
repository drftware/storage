def to_roblox(v):
    """Blender's (x, y, z) to Roblox's: x = -x, y = z, z = y."""
    return (-v[0], v[2], v[1])


def write_luau(path, battery):
    """battery: dict(size, tris) in Roblox axes (Y along it)."""

    def v3(v):
        return f"Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})"

    lines = [
        "--!strict",
        "-- Generated by art/battery/build.py --stage export from art/battery/spec.py.",
        "-- Don't edit: change the spec and rebuild (scripts/art.sh battery).",
        "-- Studs. The battery in its own frame: along Y, its button at +Y, its middle the origin.",
        "-- Radius: the wrap's, what it rolls on lying on its side.",
        "",
        "return {",
        f"\tBattery = {{ Size = {v3(battery['size'])}, Radius = {R:.3f}, "
        f"Triangles = {battery['tris']} }},",
        "}",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("SPEC", path)
