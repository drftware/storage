"""Every number of the flashlight, in studs. Change them here only.

An old plastic torch that takes two big batteries: a sun-faded yellow tube with grip rings, a black
head flaring out to the lens, a rubber button on top, a black tail cap with a wire bail for a
lanyard. Everyone carries one (GDD, the tools table).

Sized to a Roblox hand rather than to the real thing: a real one (25 cm) would be under a stud
long and vanish in an R15 fist, so it is about 1.5 times life, 1.34 studs long, and reads at phone
size in a friend's hand and in the corner of your own view.

The torch's frame in Blender: its length along Y with the lens at -Y (its front), X across, Z up
(the button on top), the origin the grip (where the hand closes round the tube). The FBX turns this
into Roblox's frame (Y up, the lens towards the part's LookVector), and the game reads the numbers
from src/shared/Flashlight/Specs.luau, which the export stage writes.
"""

