# The lens: its own MeshPart, so the game can light it (Neon when on, glass when off).
LENS = dict(y=-0.603, r=0.172, bulge=0.012)


def to_roblox(v):
    """Blender's (x, y, z) to Roblox's: x = -x, y = z, z = y."""
    return (-v[0], v[2], v[1])


def write_luau(path, body, lens):
    """body, lens: dict(size, centre, tris) in Roblox axes, from the grip."""

    def v3(v):
        return f"Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})"

    front = to_roblox((0.0, LENS["y"] - LENS["bulge"] - GRIP_Y, 0.0))
    lines = [
        "--!strict",
        "-- Generated by art/flashlight/build.py --stage export from art/flashlight/spec.py. Don't",
        "-- edit: change the spec and rebuild (scripts/art.sh flashlight).",
        "-- Studs, in the torch's own frame: its lens towards the LookVector (-Z), its button up (+Y),",
        "-- every point measured from the grip, where the hand closes round the tube.",
        "",
        "export type Piece = {",
        "\tSize: Vector3, -- the piece's box",
        "\tCentre: Vector3, -- the box's middle, from the grip",
        "\tTriangles: number,",
        "}",
        "",
        "return {",
        f"\tBody = {{ Size = {v3(body['size'])}, Centre = {v3(body['centre'])}, "
        f"Triangles = {body['tris']} }} :: Piece,",
        f"\tLens = {{ Size = {v3(lens['size'])}, Centre = {v3(lens['centre'])}, "
        f"Triangles = {lens['tris']} }} :: Piece,",
        "\t-- the middle of the lens's face, where the beam leaves",
        f"\tLensFront = {v3(front)},",
        f"\tLensRadius = {LENS['r']:.3f},",
        "\t-- the button's top, where a thumb presses",
        f"\tButton = {v3(to_roblox((0.0, BUTTON['c'][1] - GRIP_Y, BUTTON['c'][2] + BUTTON['r'][2])))},",
        "}",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("SPEC", path)
