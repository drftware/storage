def to_roblox(v):
    """Blender's (x, y, z) to Roblox's: x = -x, y = z, z = y."""
    return (-v[0], v[2], v[1])


def write_luau(path, roll, sheet):
    """roll, sheet: dict(size, centre, tris) in Roblox axes, the roll's from its grip, the sheet's
    from the middle of the floor under it."""

    def v3(v):
        return f"Vector3.new({v[0]:.3f}, {v[1]:.3f}, {v[2]:.3f})"

    def piece(p):
        return (f"{{ Size = {v3(p['size'])}, Centre = {v3(p['centre'])}, "
                f"Triangles = {p['tris']} }} :: Piece")

    lines = [
        "--!strict",
        "-- Generated by art/bubblewrap/build.py --stage export from art/bubblewrap/spec.py.",
        "-- Don't edit: change the spec and rebuild (scripts/art.sh bubblewrap).",
        "-- Studs. The roll in its own frame: its axis along X, up +Y, the taped end high on its",
        "-- front (-Z, the LookVector), every point from the grip, the middle of its axis. The sheet",
        "-- in its own: across the hall along X, up +Y, from the middle of the floor under it.",
        "",
        "export type Piece = {",
        "\tSize: Vector3, -- the piece's box",
        "\tCentre: Vector3, -- the box's middle, from the grip (the sheet's: from the floor under it)",
        "\tTriangles: number,",
        "}",
        "",
        "return {",
        f"\tBody = {piece(roll)},",
        "\t-- the roll's radius: it lies on its side this far above the floor",
        f"\tRadius = {ROLL_R * IN:.3f},",
        "\t-- the sheet Lay puts down, across the hall",
        f"\tSheet = {piece(sheet)},",
        "}",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("SPEC", path)
